#!/usr/bin/env python3
"""TritonBench-G teacher Triton rollout + correctness verify.

Reads expanded JSONL rows produced by ``InverseCoderExpansion._expand_tbg``
(``expand/methods/inversecoder.py``). For each row asks v4-pro to write a
fresh Triton implementation that respects the ref's primary_wrapper /
kernel name contract, then drops the candidate into the ref's own
test_block to compare ``result_gold`` dict-of-tensors against the gold
ref via ``torch.allclose``.

Why we still roll teacher code (vs using ref verbatim):
  - The CoT prefix in the assistant section is generated by the teacher model;
    its style + plan-then-code coherence diverges from a hand-authored ref.
    A teacher rollout produces (plan, code) written by the same model in
    one go.
  - Ref code in TritonBench-G is sometimes idiosyncratic (specific
    `BLOCK_SIZE` constants, repo-specific helpers); a teacher rollout
    normalises against our prompt format.

Pipeline:
  ┌─────────────────────────────┐
  │ expansion .jsonl row        │  (NL prompt + plan + ref + interface)
  └────────────┬────────────────┘
               │
               ▼  TEACHER_SYSTEM_TBG  → up to N format-repair attempts
  ┌─────────────────────────────┐
  │ teacher_code (Triton)       │
  └────────────┬────────────────┘
               │
               ▼  in-process subprocess (timeout)
  ┌──────────────────────────────────────────────────────────┐
  │ build candidate.py = teacher_code + ref's test_block     │
  │ run python candidate.py and python ref.py side-by-side   │
  │ compare result_gold dict via torch.allclose              │
  └──────────────────────────────────────────────────────────┘
               │
               ▼
       verify_compiled / verify_correct / verify_meta

Format check (3-stage):
  1. v4-pro <think>/<answer> wrap intact (truncation guard)
  2. exactly one ```python``` fence
  3. inside the fence: at least one @triton.jit kernel + a Python `def
     <primary_wrapper>(...)` whose name matches the ref interface

Usage:
    python scripts/teacher_triton_rollout_tbg.py \\
        --input  data/expansion/pilot/tritonbench_g_inversecoder.jsonl \\
        --output rollout/tritonbench_g_inversecoder/rollout.jsonl \\
        --max-attempts 3 \\
        --concurrency 4 \\
        --verify --gpu 0 --timeout 120
"""

