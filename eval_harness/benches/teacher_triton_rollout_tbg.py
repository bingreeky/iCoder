# Main rollout loop
# ====================================================================

async def rollout_one(row: Dict[str, Any], llm,
                      max_attempts: int,
                      do_verify: bool,
                      verify_timeout: int,
                      gpu_sem: Optional[asyncio.Semaphore],
                      max_correctness_attempts: int = 0,
                      ) -> Dict[str, Any]:
    prompt = row.get("expanded_prompt", "")
    plan = row.get("metadata", {}).get("assistant_spec", "")
    ref = row.get("reference_solution", "")
    interface = (row.get("metadata", {}).get("triton_interface")
                 or row.get("evaluator_info", {}))
    primary_wrapper = interface.get("primary_wrapper", "")
    primary_signature = interface.get("primary_signature", "")
    primary_args = ", ".join(interface.get("primary_arg_names", []) or [])
    kernel_names = interface.get("kernel_names", []) or []
    test_func_name = interface.get("test_func_name", "")
    test_block = (row.get("evaluator_info", {}).get("test_block", ""))
    # TBG uses `result_gold`, TBT uses `test_results`. The adapter sets
    # evaluator_info["test_var_name"] for TBT; default to result_gold.
    test_var_name = (row.get("evaluator_info", {})
                     .get("test_var_name", "result_gold"))

    primary_wrapper_class = (primary_wrapper.split(".")[0]
                             if "." in primary_wrapper else "")

    base_user = TEACHER_USER_TMPL_TBG.format(
        prompt=prompt, plan=plan, ref=ref,
        primary_wrapper=primary_wrapper,
        primary_signature=primary_signature,
        kernel_names=", ".join(kernel_names),
        test_func_name=test_func_name)

    sys_prompt = TEACHER_SYSTEM_TBG.format(
        primary_wrapper=primary_wrapper,
        primary_args=primary_args,
        primary_wrapper_class=primary_wrapper_class or primary_wrapper,
    )

    last_stage = ""; last_reason = ""; last_code = ""; last_traj = ""
    attempts = 0
    for attempt in range(1, max_attempts + 1):
        user = base_user
        if attempt > 1 and last_reason:
            user += TEACHER_REPAIR_SUFFIX.format(
                stage=last_stage, trace=last_reason[-1024:],
                primary_wrapper=primary_wrapper)
        attempts = attempt
        try:
            resp = await llm.chat_full(sys_prompt, user)
        except Exception as e:
            last_stage = "llm_error"
            last_reason = f"{type(e).__name__}: {e}"
            continue
        raw = resp.content or ""
        wrapped = synthesize_v4pro_wrap(
            raw, resp.reasoning_content, fallback_lang="python")
        ok_fmt, _fmt_reason = check_v4pro_format(raw)
        if not ok_fmt:
            last_stage = "v4pro_truncated"; last_reason = _fmt_reason
            last_traj = wrapped
            continue
        code = extract_code(raw)
        ok, stage, reason = format_check(code, primary_wrapper, kernel_names)
        last_code = code; last_traj = wrapped
        last_stage = stage; last_reason = reason
        if ok:
            break
    else:
        return {
            **row,
            "teacher_code": last_code,
            "teacher_traj_content": last_traj,
            "teacher_attempts": attempts,
            "teacher_status": "format_fail",
            "teacher_format_check": f"FAIL: {last_stage}: {last_reason[:200]}",
        }

    out = {
        **row,
        "teacher_code": last_code,
        "teacher_traj_content": last_traj,
        "teacher_attempts": attempts,
        "teacher_status": "ok",
        "teacher_format_check": (
            f"@triton.jit ✓ def {primary_wrapper.split('.')[-1]}(...) ✓"),
    }

    if do_verify:
        async with (gpu_sem or asyncio.Semaphore(1)):
            v = await verify_one(ref_src=ref, teacher_code=last_code,
                                 test_block=test_block,
                                 timeout=verify_timeout,
                                 test_var_name=test_var_name)
        out.update(v)

        # Closed-loop correctness repair: on inline-verify failure feed the
        # harness summary back to the teacher and re-roll. Re-runs format
        # check + verify on each repaired candidate.
        correctness_attempts = 0
        while (max_correctness_attempts > 0
               and not out.get("verify_correct")
               and correctness_attempts < max_correctness_attempts):
            correctness_attempts += 1
            summary = _summarise_verify_failure_tbg(out)
            repair_user = base_user + TEACHER_CORRECTNESS_REPAIR_SUFFIX_TBG.format(
                compiled=out.get("verify_compiled"),
                correct=out.get("verify_correct"),
                summary=summary[-1024:],
                primary_wrapper=primary_wrapper)
            try:
                resp = await llm.chat_full(sys_prompt, repair_user)
                raw = resp.content or ""
            except Exception as e:
                last_reason = f"llm_error_correctness: {type(e).__name__}: {e}"
                continue
            if not check_v4pro_format(raw)[0]:
                continue  # truncated reasoning — keep last_code
            new_code = extract_code(raw)
            ok, _, _ = format_check(new_code, primary_wrapper, kernel_names)
            if ok:
                last_code = new_code
                last_traj = synthesize_v4pro_wrap(
                    raw, resp.reasoning_content, fallback_lang="python")
            async with (gpu_sem or asyncio.Semaphore(1)):
                v = await verify_one(ref_src=ref, teacher_code=last_code,
                                     test_block=test_block,
                                     timeout=verify_timeout,
                                     test_var_name=test_var_name)
            out["teacher_code"] = last_code
            out["teacher_traj_content"] = last_traj
            out.update(v)
        out["teacher_correctness_attempts"] = correctness_attempts
        if max_correctness_attempts > 0 and not out.get("verify_correct"):
            out["teacher_status"] = "correctness_fail"

    return out


def load_rows(path: Path) -> List[Dict[str, Any]]:
    rows = []
    with path.open() as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            r = json.loads(line)
            # passthrough rows have no assistant_spec — drop them
            if not (r.get("metadata") or {}).get("assistant_spec"):
                continue
            # rows missing test_block can't be verified — drop early
            if not (r.get("evaluator_info") or {}).get("test_block"):
                continue
            rows.append(r)
    return rows


async def main_async(args) -> None:
    in_path = Path(args.input)
    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    rows = load_rows(in_path)
    print(f"[teacher-tbg] {len(rows)} rows after passthrough/missing-spec "
          f"filter (input: {in_path})", flush=True)
    if not rows:
        out_path.write_text("")
        return

    keys = []
    for suffix in ("", "1", "2", "3"):
        k = os.environ.get(f"EXPAND_LLM_API_KEY{suffix}", "").strip()
        if k:
            keys.append(k)
    if len(keys) > 1:
        llm = LLM(
            endpoint=os.environ.get("EXPAND_LLM_BASE_URL",
                                    "http://127.0.0.1:8000/v1"),
            model=os.environ.get("EXPAND_LLM_MODEL"),
            api_keys=keys,
            concurrency=args.concurrency,
            temperature=args.temperature,
            max_tokens=args.max_tokens,
        )
        print(f"[teacher-tbg] multi-key LLM: {len(keys)} keys, "
              f"concurrency={args.concurrency}", flush=True)
    else:
        llm = make_llm(dry_run=False, concurrency=args.concurrency,
                       temperature=args.temperature,
                       max_tokens=args.max_tokens)
        print(f"[teacher-tbg] single-key LLM, concurrency={args.concurrency}",
              flush=True)

    sem = asyncio.Semaphore(args.concurrency)
    # Parse GPU list for round-robin. Default "0" = single GPU.
    gpu_list = [int(g.strip()) for g in str(args.gpu).split(",") if g.strip()]
    if not gpu_list:
        gpu_list = [0]
    per_gpu_sems = {g: asyncio.Semaphore(args.gpu_concurrency) for g in gpu_list}
    _gpu_rr = [0]
    def _next_gpu() -> int:
        idx = _gpu_rr[0]
        _gpu_rr[0] = (idx + 1) % len(gpu_list)
        return gpu_list[idx]

    # Resume by scanning existing output for done ids.
    done_ids = set()
    if out_path.exists():
        with out_path.open() as f:
            for line in f:
                try:
                    done_ids.add(json.loads(line).get("id"))
                except Exception:
                    pass
    if done_ids:
        print(f"[teacher-tbg] resume: {len(done_ids)} ids already done",
              flush=True)

    todo = [r for r in rows if r.get("id") not in done_ids]
    print(f"[teacher-tbg] todo: {len(todo)} rows", flush=True)

    async def runner(row):
        async with sem:
            my_gpu = _next_gpu()
            # CUDA_VISIBLE_DEVICES env not strictly needed for verify
            # subprocess (it relies on whatever device the test_block
            # picks), but we pass the gpu through gpu_sem of that GPU's
            # bucket so concurrent verifies share that GPU's bucket.
            return await rollout_one(
                row=row, llm=llm,
                max_attempts=args.max_attempts,
                do_verify=args.verify,
                verify_timeout=args.verify_timeout,
                gpu_sem=per_gpu_sems[my_gpu],
                max_correctness_attempts=args.max_correctness_attempts)

    tasks = [asyncio.create_task(runner(r)) for r in todo]
    n_done = n_format_ok = n_correct = 0
    with out_path.open("a") as fout:
        for t in asyncio.as_completed(tasks):
            res = await t
            fout.write(json.dumps(res, ensure_ascii=False) + "\n")
            fout.flush()
            n_done += 1
            if res.get("teacher_status") == "ok":
                n_format_ok += 1
            if res.get("verify_correct"):
                n_correct += 1
            if n_done % 5 == 0 or n_done == len(tasks):
                print(f"[teacher-tbg] {n_done}/{len(tasks)} done; "
                      f"format_ok={n_format_ok} correct={n_correct}",
                      flush=True)

    print(f"[teacher-tbg] DONE: {n_done} rolled, format_ok={n_format_ok}, "
          f"correct={n_correct}", flush=True)


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser()
    p.add_argument("--input", required=True)
    p.add_argument("--output", required=True)
    p.add_argument("--max-attempts", type=int, default=3)
    p.add_argument("--concurrency", type=int, default=4)
    p.add_argument("--temperature", type=float, default=0.2)
    p.add_argument("--max-tokens", type=int, default=16384)
    p.add_argument("--verify", action="store_true",
                   help="run inline correctness verify on each row "
                        "(builds candidate.py = teacher_code + test_block, "
                        "diffs result_gold dict-of-tensors)")
    p.add_argument("--verify-timeout", type=int, default=120,
                   help="per-side subprocess timeout for verify (sec)")
    p.add_argument("--gpu", type=str, default="0",
                   help="GPU device id(s) for inline verify. Single int "
                        "(\"0\") or comma list (\"0,1,...,7\") for "
                        "round-robin across multiple GPUs.")
    p.add_argument("--gpu-concurrency", type=int, default=1,
                   help="max concurrent verify subprocesses per GPU")
    p.add_argument("--max-correctness-attempts", type=int, default=0,
                   help="closed-loop correctness-repair rounds per row "
                        "(0 = off; requires --verify). On verify failure "
                        "the harness summary is fed back to the teacher "
                        "and the kernel re-rolled; up to N rounds.")
    return p.parse_args()


def main() -> None:
    asyncio.run(main_async(parse_args()))


if __name__ == "__main__":
    main()
