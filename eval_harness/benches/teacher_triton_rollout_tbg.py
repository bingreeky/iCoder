CODE_FENCE_RE = re.compile(r"```(?:[a-zA-Z+]+)?\s*\n?(.*?)```", re.DOTALL)
TRITON_JIT_RE = re.compile(r"@triton\.jit")


TEACHER_SYSTEM_TBG = (
    "You write Triton kernels matching a fixed entry-point contract so "
    "an external test harness can invoke the result. You see a user "
    "request, an implementation plan, and the EXACT entry-point signature "
    "the harness expects. Output the implementation.\n\n"
    "OUTPUT FORMAT — exact:\n"
    "  - EXACTLY one ```python ... ``` fenced block. Nothing outside it.\n"
    "  - Inside the fence:\n"
    "      * `import torch`, `import triton`, `import triton.language as tl`\n"
    "      * One or more `@triton.jit` kernels. The hot compute path "
    "        MUST live in the kernel(s); do NOT delegate to a pure "
    "        PyTorch op.\n"
    "      * A Python wrapper `def {primary_wrapper}({primary_args})` "
    "        (EXACT name, EXACT positional argument order). Optional "
    "        keyword-only args are fine, but the positional names MUST "
    "        match the contract exactly. The wrapper allocates output "
    "        tensors, computes the launch grid, calls the kernel(s), "
    "        and returns the result tensor(s).\n"
    "      * If the contract names a class (`Cls.method`), define "
    "        `class {primary_wrapper_class}` with the same `forward` "
    "        / call signature.\n"
    "      * Output tensors must satisfy "
    "        `torch.allclose(atol=1e-2, rtol=1e-2)` against the "
    "        reference.\n"
    "  - No prose, reasoning, or markdown outside the fence."
)

TEACHER_USER_TMPL_TBG = (
    "Entry-point contract (must hit EXACTLY):\n"
    "---\n"
    "kernels (must keep names): {kernel_names}\n"
    "primary entry:             {primary_wrapper}\n"
    "entry signature:           {primary_signature}\n"
    "test function (calls primary entry; not your concern): {test_func_name}\n"
    "---\n\n"
    "User request:\n---\n{prompt}\n---\n\n"
    "Implementation plan:\n---\n{plan}\n---\n\n"
    "Triton reference (correctness oracle; do NOT copy verbatim, write "
    "your own implementation):\n```python\n{ref}\n```\n\n"
    "Now write the Triton implementation."
)

TEACHER_REPAIR_SUFFIX = (
    "\n\nYour previous attempt failed the format check.\n"
    "Stage: {stage}\n"
    "Reason:\n```\n{trace}\n```\n\n"
    "Fix it. The constraints are unchanged: one ```python``` fence; "
    "`@triton.jit` kernel(s); a `def {primary_wrapper}(...)` with "
    "EXACT positional arg order. Re-emit the FULL implementation."
)

# Closed-loop correctness repair: feeds the TBG verify failure (ref
# subprocess crash / candidate subprocess crash / result_gold mismatch)
# back to the teacher. Mirrors the KB-side closed-loop in
# scripts/teacher_triton_rollout.py.
TEACHER_CORRECTNESS_REPAIR_SUFFIX_TBG = (
    "\n\nYour previous Triton kernel passed the format check but FAILED "
    "the TBG correctness harness against the PyTorch reference.\n"
    "Verify status: compiled={compiled}, correct={correct}\n"
    "Failure summary:\n```\n{summary}\n```\n\n"
    "Common root causes:\n"
    "  - Wrong stride/contiguity assumption in tl.load / tl.store.\n"
    "  - Boundary mask missing when the test exercises non-multiple-of-"
    "BLOCK_SIZE sizes — `tl.load` without a mask reads garbage that "
    "pollutes the output.\n"
    "  - Wrong reduction axis or wrong dim ordering vs the PyTorch ref.\n"
    "  - Missing `tl.store` mask on the output side.\n"
    "  - Wrapper passed args in a different positional order than the "
    "ref / test block expects.\n\n"
    "Re-emit the FULL implementation. Constraints unchanged: one "
    "```python``` fence; `@triton.jit` kernel(s); `def {primary_wrapper}"
    "(...)` with EXACT positional arg order. The output dict written "
    "by the test block MUST match the PyTorch ref's via "
    "`torch.allclose(atol=1e-2, rtol=1e-2)`."
)


def _summarise_verify_failure_tbg(verify_result: Dict[str, Any]) -> str:
    """Render TBG verify_one's failure dict into a compact teacher prompt."""
    md = verify_result.get("verify_meta") or {}
    stage = md.get("stage", "?")
    parts = [f"stage: {stage}"]
    if md.get("error"):
        parts.append(f"error: {str(md['error'])[:400]}")
    if md.get("diff"):
        parts.append(f"diff: {str(md['diff'])[:400]}")
    return "\n".join(parts)


def extract_code(raw: str) -> str:
    if not raw:
        return ""
    answer_body = extract_v4pro_answer(raw)
    m = CODE_FENCE_RE.search(answer_body)
    return m.group(1).strip() if m else ""


def format_check(code: str, primary_wrapper: str,
                 kernel_names: List[str]) -> Tuple[bool, str, str]:
    """Return (ok, stage, reason).

    Stages: missing_fence, missing_kernel, missing_wrapper, ok.
    Kernel-name match is best-effort (we report a soft warning, not a
    hard fail, when teacher renames a kernel — the wrapper-name check
    is what actually breaks the test harness).
    """
    if not code.strip():
        return False, "missing_fence", "no ```python``` fenced block found"
    if not TRITON_JIT_RE.search(code):
        return False, "missing_kernel", "no @triton.jit kernel found"
    leaf = primary_wrapper.split(".")[-1]
    if not re.search(rf"\bdef\s+{re.escape(leaf)}\s*\(", code):
        # If the contract is a class method (`Cls.method`), accept the
        # class+method pattern too: `class Cls(...): ... def method(...)`.
        if "." in primary_wrapper:
            cls_name = primary_wrapper.split(".")[0]
            cls_re = rf"class\s+{re.escape(cls_name)}\b"
            method_re = rf"def\s+{re.escape(leaf)}\s*\("
            if re.search(cls_re, code) and re.search(method_re, code):
                return True, "ok", ""
        return False, "missing_wrapper", (
            f"no `def {leaf}(...)` wrapper found (contract requires "
            f"primary_wrapper={primary_wrapper})")
    return True, "ok", ""


# ====================================================================
# Verify: build candidate.py = teacher_code + ref test_block, run side-
# by-side with the unmodified ref, compare result_gold via torch.allclose.
# ====================================================================

_VERIFY_DRIVER = textwrap.dedent("""
    # Worker: load a python file, exec it (which assigns the test-result
    # variable — `result_gold` for TBG, `test_results` for TBT), save it
    # to a torch file, exit. Stdout: just 'OK' on success.
    import importlib.util, sys, traceback, os, torch
    ref_path = sys.argv[1]
    out_path = sys.argv[2]
    test_var = sys.argv[3] if len(sys.argv) > 3 else 'result_gold'
    spec = importlib.util.spec_from_file_location("_tbg_under_test", ref_path)
    mod = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(mod)
    except Exception:
        traceback.print_exc()
        sys.exit(2)
    rg = getattr(mod, test_var, None)
    if rg is None:
        print(f'{test_var} attribute missing', file=sys.stderr)
        sys.exit(3)
    # Coerce to dict-of-tensors / dict-of-cpu-tensors for transport.
    def to_cpu(x):
        if isinstance(x, torch.Tensor): return x.detach().cpu()
        if isinstance(x, (list, tuple)): return type(x)(to_cpu(v) for v in x)
        if isinstance(x, dict): return {k: to_cpu(v) for k,v in x.items()}
        return x
    torch.save({'result_gold': to_cpu(rg)}, out_path)
    print('OK')
""").strip()


def _read_saved_result_gold(path: Path) -> Any:
    import torch
    return torch.load(path, weights_only=False)["result_gold"]


def _allclose_dict(a: Any, b: Any, atol: float = 1e-2,
                   rtol: float = 1e-2) -> Tuple[bool, str]:
    """Recursively compare two values. Returns (match, reason). Reason
    is non-empty on failure."""
    import torch
    if type(a) != type(b):
        return False, f"type mismatch: {type(a).__name__} vs {type(b).__name__}"
    if isinstance(a, dict):
        if set(a.keys()) != set(b.keys()):
            return False, f"key mismatch: {sorted(a.keys())} vs {sorted(b.keys())}"
        for k in a:
            ok, why = _allclose_dict(a[k], b[k], atol, rtol)
            if not ok:
                return False, f"key={k!r}: {why}"
        return True, ""
    if isinstance(a, (list, tuple)):
        if len(a) != len(b):
            return False, f"len mismatch: {len(a)} vs {len(b)}"
        for i, (x, y) in enumerate(zip(a, b)):
            ok, why = _allclose_dict(x, y, atol, rtol)
            if not ok:
                return False, f"idx={i}: {why}"
        return True, ""
    if isinstance(a, torch.Tensor):
        if a.shape != b.shape:
            return False, f"shape mismatch: {tuple(a.shape)} vs {tuple(b.shape)}"
        if a.dtype != b.dtype:
            # cast both to fp32 for comparison; dtype mismatch alone is
            # not a fail (teacher might use a wider accumulator)
            a = a.float(); b = b.float()
        if not torch.allclose(a, b, atol=atol, rtol=rtol, equal_nan=True):
            # int / bool dtypes can't .mean() — promote diff to float for
            # the diagnostic stats. Use abs() then float() so neg deltas
            # don't underflow signed-int range either.
            diff = (a - b).abs().float()
            return False, (f"max_diff={diff.max().item():.4g} "
                           f"mean_diff={diff.mean().item():.4g}")
        return True, ""
    try:
        import numpy as np
        if isinstance(a, np.ndarray):
            if a.shape != b.shape:
                return False, f"shape mismatch: {a.shape} vs {b.shape}"
            if not np.allclose(a, b, atol=atol, rtol=rtol, equal_nan=True):
                diff = np.abs(a.astype(np.float64) - b.astype(np.float64))
                return False, f"max_diff={diff.max():.4g} mean_diff={diff.mean():.4g}"
            return True, ""
    except ImportError:
        pass
    # scalar / int / str / None — direct equality. Wrap in bool() to defang
    # any container that overrides __eq__ to return an array (numpy scalars
    # that slip past the isinstance check above, custom types, etc.).
    try:
        eq = bool(a == b)
    except (ValueError, TypeError):
        eq = False
    return (eq, "" if eq else f"value mismatch: {a!r} vs {b!r}")


async def verify_one(ref_src: str, teacher_code: str, test_block: str,
                     timeout: int = 120,
                     test_var_name: str = "result_gold") -> Dict[str, Any]:
    """Run ref + candidate side-by-side, compare result_gold (TBG) or
    test_results (TBT) dict."""
    import tempfile
    with tempfile.TemporaryDirectory(prefix="tbg_verify_") as tmp:
        tmpd = Path(tmp)
        ref_p = tmpd / "ref.py"
        cand_p = tmpd / "cand.py"
        ref_out = tmpd / "ref.pt"
        cand_out = tmpd / "cand.pt"
        ref_p.write_text(ref_src)
        cand_p.write_text(teacher_code + "\n\n" + test_block)

        async def _run(fp: Path, out: Path) -> Tuple[int, str]:
            try:
                proc = await asyncio.create_subprocess_exec(
                    sys.executable, "-c", _VERIFY_DRIVER,
                    str(fp), str(out), test_var_name,
                    stdout=asyncio.subprocess.PIPE,
                    stderr=asyncio.subprocess.PIPE,
                )
            except FileNotFoundError as e:
                return -1, f"launch failed: {e}"
            try:
                _, stderr = await asyncio.wait_for(
                    proc.communicate(), timeout=timeout)
            except asyncio.TimeoutError:
                proc.kill(); await proc.wait()
                return -1, f"timeout ({timeout}s)"
            return proc.returncode, stderr.decode("utf-8", errors="ignore")[-1024:]

        # Run ref first so we have a known-good gold to compare against.
        rc_ref, err_ref = await _run(ref_p, ref_out)
        if rc_ref != 0:
            return {
                "verify_compiled": False,
                "verify_correct": False,
                "verify_skipped": True,  # ref unrunnable -> unwinnable for any model
                "verify_meta": {
                    "stage": "ref_smoke_failed",
                    "error": err_ref or f"rc={rc_ref}",
                },
            }
        rc_c, err_c = await _run(cand_p, cand_out)
        if rc_c != 0:
            return {
                "verify_compiled": False,
                "verify_correct": False,
                "verify_meta": {
                    "stage": "candidate_run_failed",
                    "error": err_c or f"rc={rc_c}",
                },
            }
        # Both ran — diff result_gold.
        try:
            ref_rg = _read_saved_result_gold(ref_out)
            cand_rg = _read_saved_result_gold(cand_out)
        except Exception as e:
            return {
                "verify_compiled": True, "verify_correct": False,
                "verify_meta": {
                    "stage": "result_load_failed",
                    "error": f"{type(e).__name__}: {e}",
                },
            }
        ok, why = _allclose_dict(ref_rg, cand_rg)
        return {
            "verify_compiled": True,
            "verify_correct": ok,
            "verify_meta": {
                "stage": "ok" if ok else "allclose_failed",
                "diff": why if not ok else "",
            },
        }


